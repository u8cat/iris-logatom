(** The mathematical model of a data structure exposing a single operation, where:
  - [f s v s'] specifies that calling the operation on a structure at state [s]
    with argument [v] results in an updated state [s'];
  - [r s v v'] specifies that calling the operation on a structure at state [s]
    with argument [v] produces a result value [v']. *)
Class model := {
  S : Set;
  s_init : S;
  valid_requests : list (val → Prop);
  request_responses : list (S → val → S → val → Prop);
}.

Definition default_vr : val → Prop := λ _, False.
Definition default_rr `{model} : S → val → S → val → Prop := λ _ _ _ _, False.

Global Instance S_inhabited `{M : model} : Inhabited S := populate s_init.

(** A formal definition of linearizability of a library.
  Birkedal et al. [2021] has formalized the notation of lineariability as trace
  property. However, to migrate their definition to a library, we need a client
  to generate some traces. We introduce the notion of most adversarial client,
  and define that a library is linearizable iff the trace of using this library
  generated by a most adversarial client is lineariable. *)

(* A trace is tagged by a unique ID τ. *)
Inductive trace : Set :=
  | Call (op : nat) (request : val)
  | Lin (op : nat) (request result : val)
  | Ret (result : val).

Definition encode_lin_trace (t : trace) :=
  match t with
  | Call op v => InjLV (#op, v)
  | Lin op v v' => (#op,v,v')%V
  | Ret v => InjRV v
  end.

Definition decode_lin_trace (v : val) :=
  match v with
  | InjLV (#(LitInt z), v) =>
    if bool_decide (0 ≤ z)%Z then
      Some (Call (Z.to_nat z) v)
    else
      None
  | (#(LitInt z), v,v')%V =>
    if bool_decide (0 ≤ z)%Z then
      Some (Lin (Z.to_nat z) v v')
    else
      None
  | InjRV v => Some (Ret v)
  | _ => None
  end.

Definition is_call t :=
  if t is Call _ _ then True else False.

Definition is_lin t :=
  if t is Lin _ _ _ then True else False.

Definition is_ret t :=
  if t is Ret _ then True else False.

Global Instance trace_inhabited : Inhabited trace := populate (Call 0 #()).

Global Instance trace_eqdecision : EqDecision trace.
Proof. solve_decision. Defined.

Global Program Instance trace_encodable : Encodable trace := {
  encode_val := encode_lin_trace;
  decode_val := decode_lin_trace;
}.
Next Obligation.
  intros [n v|n v v'|v']; try reflexivity.
  - simpl. rewrite bool_decide_eq_true_2; last lia.
    do 2 f_equal. lia.
  - simpl. rewrite bool_decide_eq_true_2; last lia.
