Lemma per_tag_partial_linearized_inj_call_index ts τ i j n1 v1 n2 v2 :
  per_tag_partial_linearized ts →
  ts !! i = Some (τ, Call n1 v1) → ts !! j = Some (τ, Call n2 v2) →
  i = j.
Proof.
  intros Hwf Hlookup1 Hlookup2.
  apply dec_stable. intros ?.
  destruct (Hwf τ) as (n & v & v' & Hsubstr).
  destruct (decide (i < j)) as [?|?].
  - pose proof (take_drop_middle _ _ _ Hlookup2) as Heq.
    rewrite -(lookup_take_lt _ j) in Hlookup1; last lia.
    destruct (list_elem_of_split_length _ _ _ Hlookup1) as (l1 & l2 & Hrw & _).
    rewrite Hrw in Heq.
    apply (f_equal (filter (λ x, x.1 = τ))) in Heq.
    rewrite !filter_app !filter_cons_True // in Heq.
    rewrite -Heq in Hsubstr.
    apply (substr_filter (is_call∘snd)) in Hsubstr.
    rewrite !filter_app !filter_cons /= filter_nil in Hsubstr.
    apply substr_length in Hsubstr.
    rewrite !length_app !length_cons length_nil in Hsubstr.
    lia.
  - pose proof (take_drop_middle _ _ _ Hlookup1) as Heq.
    rewrite -(lookup_take_lt _ i) in Hlookup2; last lia.
    destruct (list_elem_of_split_length _ _ _ Hlookup2) as (l1 & l2 & Hrw & _).
    rewrite Hrw in Heq.
    apply (f_equal (filter (λ x, x.1 = τ))) in Heq.
    rewrite !filter_app !filter_cons_True // in Heq.
    rewrite -Heq in Hsubstr.
    apply (substr_filter (is_call∘snd)) in Hsubstr.
    rewrite !filter_app !filter_cons /= filter_nil in Hsubstr.
    apply substr_length in Hsubstr.
    rewrite !length_app !length_cons length_nil in Hsubstr.
    lia.
Qed.

