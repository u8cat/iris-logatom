Lemma library_initializable_linearizable_destruct `{M : model} init op :
  library_initializable_linearizable init op →
  ∃ valid_obj, library_initializable init valid_obj ∧ library_linearizable op valid_obj.
Proof.
  intros [Hadq Hlin].
  exists (λ op σ, ∃ σ₀ t, rtc erased_step ([init], σ₀) (Val op::t, σ)).
  split.
  - intros σ₀. specialize (Hadq σ₀). constructor.
    + intros t2 σ2 v2 Hsteps. exists σ₀, t2.
      exact Hsteps.
    + eapply adequate_not_stuck. eassumption.
  - intros obj σ config' ts (σ₀ & t & Hsteps) Hadv_steps.
    eauto.
Qed.

Lemma library_initializable_linearizable_combine `{M : model} init op valid_obj :
  library_initializable init valid_obj → library_linearizable op valid_obj →
  library_initializable_linearizable init op.
Proof.
  intros Hinit Hop. split.
  - intros σ. destruct (Hinit σ). constructor; eauto.
  - intros obj σ₀ t σ config' ts Hsteps Hadv_steps.
    eapply Hop; last eassumption.
    destruct (Hinit σ₀). eauto.
Qed.

Lemma library_initializable_linearizable_iff `{M : model} init op :
  library_initializable_linearizable init op ↔
  ∃ valid_obj, library_initializable init valid_obj ∧ library_linearizable op valid_obj.
Proof.
  split.
  - apply library_initializable_linearizable_destruct.
  - intros (?&?&?). eapply library_initializable_linearizable_combine; eassumption.
Qed.
