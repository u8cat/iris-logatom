    do 4 f_equal. lia.
  - do 4 (case_match; try discriminate Hdec).
    rename select (bool_decide _ = true) into Hn.
    apply bool_decide_eq_true_1 in Hn.
    simplify_eq. simpl.
    do 4 f_equal. lia.
Qed.

