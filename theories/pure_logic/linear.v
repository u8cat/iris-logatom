  - left; done.
  - right.
    destruct Hsubstr as (l1 & l2 & Hsubstr).
    destruct l1 as [|? l1].
    { (* impossible *)
      rewrite left_id_L -!app_comm_cons in Hsubstr.
      injection Hsubstr as HFalse.
      discriminate HFalse. }
    assert (length l1 = 0 ∧ length xs = 0 ∧ length l2 = 0) as (?&?&?).
    { apply (f_equal length) in Hsubstr.
      rewrite !length_app /= in Hsubstr. lia. }
    destruct l1; last done.
    destruct xs; last done.
    destruct l2; last done.
    rewrite right_id_L /= in Hsubstr.
