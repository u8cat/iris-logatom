      { symmetry. apply list_filter_filter_l.
        intros [τ_a t_a] Heq. simpl in Heq. simpl. subst τ_a. exact Hnotin. }
      assert (Hlen_le1 : length (filter (λ x : positive*trace, x.1 = τ) ts1) ≤ 1).
