(** Pure steps of one thread commute with steps of the other threads, so a pure
  step may be deleted from a derivation -- provided the derivation really does
  run that thread past it.  Both restrictions in [erased_steps_pure_steps_ctx]
  below are needed:

  - the thread must reach a value.  Otherwise take the *reflexive* derivation:
    the conclusion would have to step [e2] back to [e1].  (This also refutes
    [erased_steps_pure_steps_1] in [pure_logic/steps.v], with [K := []].)

  - the hole must sit in the operator of an application whose two arguments are
    the pure subterm and an arbitrary expression, not under an arbitrary [ctx].
    Under a binder the pure subterm is not in an evaluation position and can even
    be duplicated: for [C := [CTX_Rec BAnon BAnon]] the two sides reach the two
    distinct values [rec: <> <> := e1] and [rec: <> <> := e2]. *)

Section pure_steps.
  Implicit Types (e : expr) (t : list expr) (σ : state).

  (** [erased_step] as an update of one thread plus the forked threads. *)
  Local Lemma erased_step_insert t σ t' σ' :
    erased_step (t, σ) (t', σ') →
    ∃ i e e' κ efs,
      t !! i = Some e ∧ prim_step e σ κ e' σ' efs ∧ t' = <[i:=e']>t ++ efs.
  Proof.
    intros [κ Hstep].
    inversion Hstep as [ea σa eb σb efs t1 t2 Heq1 Heq2 Hprim]; simplify_eq.
    exists (length t1), ea, eb, κ, efs. split_and!; [|done|].
    - by rewrite list_lookup_middle.
    - rewrite insert_app_r_alt // Nat.sub_diag /=.
      by rewrite -app_assoc.
  Qed.

  Local Lemma erased_step_insert' t σ σ' i e e' κ efs :
    t !! i = Some e →
    prim_step e σ κ e' σ' efs →
    erased_step (t, σ) (<[i:=e']>t ++ efs, σ').
  Proof.
    intros Hi Hprim.
    pose proof (lookup_lt_Some _ _ _ Hi) as Hlt.
    pose proof (take_drop_middle _ _ _ Hi) as Ht.
    assert (length (take i t) = i) as Hlen by (rewrite length_take; lia).
    exists κ. eapply (step_atomic e σ e' σ' efs (take i t) (drop (S i) t));
      [by rewrite Ht|f_equal|done].
    rewrite insert_take_drop // -app_assoc //.
  Qed.

  (** A single pure step of thread [k] can be deleted, unless the derivation
    never touches that thread (in which case it is still there at the end). *)
  Local Lemma erased_nsteps_pure_step_commute n e1 e2 k t σ t' σ' :
    pure_step e1 e2 →
    t !! k = Some e1 →
    relations.nsteps erased_step n (t, σ) (t', σ') →
    rtc erased_step (<[k:=e2]>t, σ) (t', σ') ∨ t' !! k = Some e1.
  Proof.
    intros Hpure. revert t σ.
    induction n as [|n IH] => t σ Hk Hns.
    { inversion Hns; simplify_eq. by right. }
    inversion Hns as [|? ? ρm ? Hstep Hns']; simplify_eq.
    destruct ρm as [tm σm].
    apply erased_step_insert in Hstep as (i & e & e' & κ & efs & Hi & Hprim & ->).
    pose proof (lookup_lt_Some _ _ _ Hk) as Hklt.
    destruct (decide (i = k)) as [->|Hne].
    - (* the distinguished thread steps: by determinism this is the pure step *)
      left. assert (e = e1) as -> by congruence.
      destruct Hpure as [_ Hdet].
      destruct (Hdet _ _ _ _ _ Hprim) as (_ & -> & -> & ->).
      rewrite right_id_L in Hns'. by eapply rtc_nsteps_2.
    - (* another thread steps: replay it and recurse *)
      assert (Hne' : k ≠ i) by congruence.
      assert (Hm : (<[i:=e']>t ++ efs) !! k = Some e1).
      { rewrite lookup_app_l; last by rewrite length_insert.
        by rewrite list_lookup_insert_ne. }
      destruct (IH _ _ Hm Hns') as [Hrest|Hstill]; last by right.
      left. eapply rtc_l; last exact Hrest.
      rewrite insert_app_l; last by rewrite length_insert.
      rewrite (list_insert_insert_ne _ k i _ _ Hne').
      eapply erased_step_insert'; last exact Hprim.
      by rewrite list_lookup_insert_ne.
  Qed.

  Local Lemma erased_steps_pure_step_val e1 e2 k t σ t' σ' (v : val) :
    pure_step e1 e2 →
    t !! k = Some e1 →
    t' !! k = Some (of_val v) →
    rtc erased_step (t, σ) (t', σ') →
    rtc erased_step (<[k:=e2]>t, σ) (t', σ').
  Proof.
    intros Hpure Hk Hv [n Hns]%rtc_nsteps_1.
    destruct (erased_nsteps_pure_step_commute n e1 e2 k t σ t' σ')
      as [?|Hstill]; [done..|].
    (* the thread was never stepped, contradicting that it is a value at the end *)
    rewrite Hstill in Hv. injection Hv as ->.
    destruct Hpure as [Hsafe _].
    assert (Hred : reducible (of_val v) σ).
    { destruct (Hsafe σ) as (? & ? & ? & ?). by do 4 eexists. }
    apply reducible_not_val in Hred. discriminate Hred.
  Qed.

  Local Lemma erased_steps_pure_steps_val_idx e1 e2 k t σ t' σ' (v : val) :
    rtc pure_step e1 e2 →
    t !! k = Some e1 →
    t' !! k = Some (of_val v) →
    rtc erased_step (t, σ) (t', σ') →
    rtc erased_step (<[k:=e2]>t, σ) (t', σ').
  Proof.
    intros Hpures. revert t.
    induction Hpures as [e|e ea e2 Hstep Hpures IH] => t Hk Hv Hsteps.
    { by rewrite list_insert_id. }
    opose proof (erased_steps_pure_step_val e ea k t σ t' σ' v _ Hk Hv Hsteps)
      as Hsteps'; first done.
    opose proof (IH (<[k:=ea]>t) _ Hv Hsteps') as Hsteps''.
    { apply list_lookup_insert_eq. by eapply lookup_lt_Some. }
    by rewrite list_insert_insert_eq in Hsteps''.
  Qed.

  (** The evaluation-context core, in the shape of [erased_steps_pure_steps_1]. *)
  Local Lemma erased_steps_pure_steps_val K e1 e2 σ1 σ2 ts0 ts1 ts2 (v : val) :
    rtc pure_step e1 e2 →
    ts2 !! length ts0 = Some (of_val v) →
    rtc erased_step (ts0++fill K e1::ts1, σ1) (ts2,σ2) →
    rtc erased_step (ts0++fill K e2::ts1, σ1) (ts2,σ2).
  Proof.
    intros Hpures Hv Hsteps.
    opose proof (erased_steps_pure_steps_val_idx (fill K e1) (fill K e2)
                   (length ts0) _ σ1 ts2 σ2 v _ _ Hv Hsteps) as Hsteps'.
    - clear -Hpures. induction Hpures as [|e ea e2' Hstep Hpures IH]; first done.
      eapply rtc_l; last exact IH. by apply (pure_step_ctx (fill K)).
    - by rewrite list_lookup_middle.
    - rewrite insert_app_r_alt in Hsteps'; last done.
      by rewrite Nat.sub_diag /= in Hsteps'.
  Qed.
End pure_steps.

(** * Contexts through which pure steps of the hole can be deleted

  [fill K] qualifies: the hole is in an evaluation position, so it pure-steps
  along with the whole thread.  But more is allowed: the hole may be *temporarily
  blocked* by a sibling expression, as in [App (f ▢) e0], where heap_lang
  evaluates [e0] first and only then the hole.  A derivation can be split at the
  point where the blocking expression has become a value, and from there on the
  hole is in an evaluation position again.  Closing the two shapes under nesting
  gives the class below.

  A binder can never qualify: under [Rec f x ▢] the hole is *never* reduced, yet
  the thread reaches a value, and the two sides reach the two distinct values
  [RecV f x e1] and [RecV f x e2].  So no premise about the target can extend
  this to arbitrary [ctx]s. *)
Inductive pure_ctx : (expr → expr) → Prop :=
  (** the hole is in an evaluation position *)
  | pure_ctx_fill (C : expr → expr) (K : list ectx_item) :
      (∀ e, C e = fill K e) →
      pure_ctx C
  (** the hole is blocked by [e0], which is itself in an evaluation position;
    once [e0] has become a value [w], the hole sits in [D w] *)
  | pure_ctx_block (C : expr → expr) (K : expr → list ectx_item)
                   (e0 : expr) (D : val → expr → expr) :
      (∀ e, C e = fill (K e) e0) →
      (∀ e (w : val), fill (K e) (of_val w) = D w e) →
      (∀ w, pure_ctx (D w)) →
      pure_ctx C.

(** The canonical blocked shape: [(K[▢]) e0] with [e0] an arbitrary expression.
  Nest it to block the hole several times over. *)
Lemma pure_ctx_app_block (K : list ectx_item) (e0 : expr) :
  pure_ctx (λ e, App (fill K e) e0).
Proof.
  eapply (pure_ctx_block _ (λ e, [AppRCtx (fill K e)]) e0
            (λ w e, App (fill K e) (of_val w))); [done|done|].
  intros w. apply (pure_ctx_fill _ (K ++ [AppLCtx w])).
  intros e. by rewrite fill_app.
Qed.

Lemma erased_steps_pure_steps_ctx C e1 e2 σ1 σ2 (v : val) ts1 ts2 :
  pure_ctx C →
  rtc pure_step e1 e2 →
  rtc erased_step (C e1 :: ts1, σ1) (of_val v :: ts2, σ2) →
  rtc erased_step (C e2 :: ts1, σ1) (of_val v :: ts2, σ2).
Proof.
  intros HC. revert e1 e2 σ1 σ2 v ts1 ts2.
  induction HC as [C K HCK|C K e0 D H1 H2 HD IH]
    => e1 e2 σ1 σ2 v ts1 ts2 Hpures Hsteps.
  - (* the hole is in an evaluation position: commute the pure steps *)
    rewrite HCK in Hsteps. rewrite HCK.
    by eapply (erased_steps_pure_steps_val K e1 e2 σ1 σ2 [] ts1).
  - (* split the derivation where [e0] has become a value, recurse, re-attach *)
    rewrite H1 in Hsteps.
    apply rtc_nsteps_1 in Hsteps as [n Hsteps].
    apply (erased_nsteps_bind_inv _ _ _ _ v _ _ _) in Hsteps
      as (w & t2 & σ & Hinit & Hrest).
    assert (Hrest2 : rtc erased_step (D w e1 :: t2, σ) (of_val v :: ts2, σ2)).
    { rewrite -(H2 e1 w). exact Hrest. }
    opose proof (IH w e1 e2 σ σ2 v t2 ts2 Hpures Hrest2) as Hrest'.
    rewrite -(H2 e2 w) in Hrest'.
    rewrite H1. eapply erased_steps_apply_head; first exact Hinit.
    exact Hrest'.
Qed.
